// ---- Service_Catalog (authored input → derived catalog) ----

export interface CatalogItemInput {
  name: string;
  /** Placeholder description, 1–3 sentences, ≤400 chars (Req 2.6). */
  description: string;
}
export interface CatalogCategoryInput {
  name: ServiceCategoryName;
  /** 1–2 sentences, ≤250 chars, names the trade's team, crew or specialists once (Req 2.5, 27.9). */
  summary: string;
  icon: IconName;
  headerPhoto: PhotoId;
  /** requirements.md Appendix A verbatim, in order. */
  items: CatalogItemInput[];
}
export type CatalogInput = CatalogCategoryInput[];

export interface ServiceItem {
  name: string;
  slug: string;
  description: string;
}
export interface ServiceCategory {
  name: ServiceCategoryName;
  slug: CategorySlug;
  summary: string;
  icon: IconName;
  headerPhoto: PhotoId;
  items: ServiceItem[];
}
export interface ServiceCatalog {
  /** Exactly 7, in CATEGORY_NAMES order. */
  categories: ServiceCategory[];
  bySlug: ReadonlyMap<string, ServiceCategory>;
}
export interface FilteredCategory {
  category: ServiceCategory;
  items: ServiceItem[];
}

// ---- Photos (generated by scripts/optimize-photos.mjs) ----

/** Slot id from the design's Photo slots table, e.g. 'home-hero', 'category-outdoor-living'. */
export type PhotoId = string;

export interface Photo {
  id: PhotoId;
  /** Intrinsic size of the largest file (or the slot's nominal size while `sources` is empty). */
  width: number;
  height: number;
  /** The 640, 1280 and 1920 px WebP files (Vite-imported URLs), for srcset. */
  sources: { src: string; width: number }[];
  /** CSS object-position value, e.g. '50% 40%'. */
  focal: string;
}
// A slot with no files yet (empty `sources`) renders the SmartImage placeholder.

// ---- Projects ----

export interface Project extends PlaceholderFlag {
  id: string;
  /** 1–60 chars. */
  title: string;
  category: ServiceCategoryName;
  /** 1–2 sentences, ≤200 chars. */
  description: string;
  photo: PhotoId;
  /** ≤150 chars, describes the subject. */
  alt: string;
}

// ---- Reviews ----

export interface Review extends PlaceholderFlag {
  id: string;
  /** /^[A-Za-z]{2,20} [A-Z]\.$/, e.g. 'Maria S.' */
  reviewerName: string;
  /** Must be in serviceAreas.cities. */
  city: string;
  category: ServiceCategoryName;
  rating: 1 | 2 | 3 | 4 | 5;
  /** 1–4 sentences, 1–400 chars. */
  text: string;
  /** Exactly three reviews are featured. */
  featured: boolean;
}
export interface RatingSummary {
  /** One decimal digit, e.g. '4.3'. */
  averageText: string;
  count: number;
  /** 'Based on 1 review' | 'Based on N reviews'. */
  countText: string;
}

// ---- FAQ ----

export type RichText = Array<string | { type: 'link'; to: string; text: string }>;
export type FaqTopic =
  | 'free-estimates'
  | 'licensing-insurance'
  | 'warranties'
  | 'timelines'
  | 'storm-damage-claims'
  | 'permits'
  | 'homeowner-present'
  | 'payment-methods'
  | 'cleanup'
  | 'service-area'
  | 'other';
export interface FaqItem extends PlaceholderFlag {
  id: string;
  /** 1–120 chars, ends with "?". */
  question: string;
  /** 1–4 sentences, 1–600 chars of text. */
  answer: RichText;
  /** The Req 19.4 topic this item covers. */
  topic: FaqTopic;
}
export interface FaqGroup {
  /** Slug, e.g. 'estimates-and-scheduling'. */
  id: string;
  /** Rendered as h2, e.g. 'Estimates and scheduling'. */
  title: string;
  /** ≥ 1 item. */
  items: FaqItem[];
}
/**
 * 3–4 groups in display order; `groups.flatMap(g => g.items)` is the FAQ_Item order of
 * the Content_Module.
 */
export type FaqContent = FaqGroup[];

// ---- Contact, social, maps, site text ----

/** Shown on the Contact_Page and in the Footer. The Website shows no street address. */
export interface ContactDetails extends PlaceholderFlag {
  /** '(214) 555-0123' */
  phone: string;
  /** 'info@dtgoelite.example' */
  email: string;
  /** 'Mon–Fri 7:00 AM – 6:00 PM, Sat 8:00 AM – 2:00 PM' */
  hours: string;
  /** 'Based in Dallas, TX, serving the greater Dallas–Fort Worth area' */
  locationLine: string;
}
export type SocialPlatform = 'Facebook' | 'Instagram' | 'Google Business Profile' | 'Nextdoor';
export interface SocialLink extends PlaceholderFlag {
  platform: SocialPlatform;
  url: string;
}
export interface MapEmbedConfig extends PlaceholderFlag {
  /** Contact_Page: https://maps.google.com/maps?q=Dallas%2C%20TX&z=11&output=embed */
  embedUrl: string;
  /** Contact_Page: https://www.google.com/maps/search/?api=1&query=Dallas%2C%20TX */
  openUrl: string;
  /** ≤100 chars; Contact_Page: 'Map of Dallas, TX, home base of D&T Go Elite' */
  title: string;
  /** Place name shown in the fallback; Contact_Page: 'Dallas, TX' */
  label: string;
}
export interface ServiceAreasContent extends PlaceholderFlag {
  intro: string;
  note: string;
  /** 15–40 unique names. */
  cities: string[];
  /** q=Dallas-Fort%20Worth%2C%20TX&z=9&output=embed */
  map: MapEmbedConfig;
}
export interface AboutContent extends PlaceholderFlag {
  /** Page-header intro under the h1. */
  intro: string;
  /** 2–3 paragraphs. */
  story: string[];
  /** About image (4:5) beside the story. */
  photo: PhotoId;
  alt: string;
  /** 3–6 values. */
  values: { title: string; description: string }[];
  stats: {
    yearsInBusiness: string;
    projectsCompleted: string;
    satisfaction: string;
    serviceRadiusMiles: number;
  };
  /** Req 9.4; `text` has a '{radius}' token filled from stats.serviceRadiusMiles. */
  serviceArea: { heading: string; text: string };
}
export interface HomeContent extends PlaceholderFlag {
  /** No Tagline; the photo shows roofing work (Req 6.1). */
  hero: { headline: string; sentence: string; photo: PhotoId; alt: string };
  /** Exactly 4. */
  highlights: { icon: IconName; title: string; text: string }[];
  /** Exactly 4, fixed order. */
  steps: { title: string; text: string }[];
  closing: ClosingBanner;
}
export interface SiteContent extends PlaceholderFlag {
  /** Placeholder proposal, 1–6 words, shown in the Footer only (Req 27.1, 27.2). */
  tagline: string;
  /** One sentence, ≤160 chars. */
  footerDescription: string;
  /** Footer "Concept demo" notice (Req 1.6). */
  conceptNotice: string;
  reviewSampleNotice: string;
  leaveReviewUrl: string;
  /** Not_Found_Page h1 and sentence (Req 5.7). */
  notFound: { heading: string; text: string };
}

